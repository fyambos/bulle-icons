import fs from 'node:fs/promises'
import path from 'node:path'
import { dirs, GRID, font } from './config.mjs'
import { camel, log, writeJson } from './lib.mjs'

// Names a module cannot declare, and the names of the exports that are not icons.
const TAKEN = new Set([
  'arguments', 'await', 'break', 'case', 'catch', 'class', 'const', 'continue', 'debugger', 'default', 'delete',
  'do', 'else', 'enum', 'eval', 'export', 'extends', 'false', 'finally', 'for', 'function', 'if', 'implements',
  'import', 'in', 'instanceof', 'interface', 'let', 'new', 'null', 'package', 'private', 'protected', 'public',
  'return', 'static', 'super', 'switch', 'this', 'throw', 'true', 'try', 'typeof', 'var', 'void', 'while', 'with',
  'yield', 'viewBox', 'icons', 'iconNames', 'getIcon', 'toSvg'
])

// Export name of an icon, "icon" is added before a digit and "Icon" after a taken name.
export function exportName (name) {
  const c = camel(name)
  const id = /^[0-9]/.test(c) ? `icon${c[0].toUpperCase()}${c.slice(1)}` : c
  return TAKEN.has(id) ? `${id}Icon` : id
}

// Functions of both module formats, they read the icons object declared above them.
const functions = (baseline) => `function getIcon (name) {
  return Object.hasOwn(icons, name) ? icons[name] : null
}

// Standalone <svg> string, sized in em and lowered like the glyph to sit in a line of text.
function toSvg (name, { size = '1em', className, label, ...attrs } = {}) {
  const body = getIcon(name)
  if (body == null) throw new Error(\`[bulle] unknown icon: \${name}\`)

  const a = {
    xmlns: 'http://www.w3.org/2000/svg',
    viewBox,
    width: size,
    height: size,
    fill: 'currentColor',
    style: 'vertical-align:${baseline}',
    ...(className ? { class: className } : null),
    ...(label ? { role: 'img', 'aria-label': label } : { 'aria-hidden': 'true' }),
    ...attrs
  }

  const serialised = Object.entries(a)
    .map(([k, v]) => \` \${k}="\${String(v).replace(/"/g, '&quot;')}"\`)
    .join('')

  return \`<svg\${serialised}>\${body}</svg>\`
}`

// Writes icons.json and the JavaScript module in both formats, with its types.
export async function buildJs (icons, { distDir = dirs.dist } = {}) {
  const viewBox = `0 0 ${GRID} ${GRID}`
  const baseline = `-${font.descent / font.fontHeight}em`
  const named = icons.map((i) => ({ ...i, id: exportName(i.name) }))

  const seen = new Map()

  for (const { id, name } of named) {
    if (seen.has(id)) throw new Error(`${name} and ${seen.get(id)} have the same export name, ${id}`)
    seen.set(id, name)
  }

  await writeJson(
    path.join(distDir, 'icons.json'),
    Object.fromEntries(
      icons.map((i) => [i.name, {
        body: i.body,
        viewBox,
        codepoint: i.codepoint,
        category: i.category,
        keywords: i.keywords
      }])
    )
  )

  // Each icon is declared on its own, so a bundler keeps only the imported ones.
  const esm = `// Generated by build/js.mjs, do not edit.

export const viewBox = ${JSON.stringify(viewBox)}

${named.map((i) => `const $${i.id} = ${JSON.stringify(i.body)}`).join('\n')}

${named.map((i) => `export const ${i.id} = { name: ${JSON.stringify(i.name)}, body: $${i.id}, viewBox }`).join('\n')}

// Icon name to inner SVG markup.
export const icons = {
${named.map((i) => `  ${JSON.stringify(i.name)}: $${i.id}`).join(',\n')}
}

export const iconNames = /* @__PURE__ */ Object.keys(icons)

${functions(baseline).replace(/^function /gm, 'export function ')}
`

  await fs.writeFile(path.join(distDir, 'index.js'), esm)

  const cjs = `// Generated by build/js.mjs, do not edit.
'use strict'
const data = require('./icons.json')

const viewBox = ${JSON.stringify(viewBox)}
const icons = Object.fromEntries(Object.entries(data).map(([name, icon]) => [name, icon.body]))

${functions(baseline)}

module.exports = { viewBox, icons, iconNames: Object.keys(icons), getIcon, toSvg }

// Export name and icon name of each icon.
const NAMED = ${JSON.stringify(named.map((i) => [i.id, i.name]))}

for (const [id, name] of NAMED) module.exports[id] = { name, body: icons[name], viewBox }
`
  await fs.writeFile(path.join(distDir, 'index.cjs'), cjs)

  const names = icons.length
    ? icons.map((i) => `  | ${JSON.stringify(i.name)}`).join('\n')
    : '  | never'

  const dts = `// Generated by build/js.mjs, do not edit.

export type IconName =
${names}

export interface Icon {
  name: IconName
  body: string
  viewBox: string
}

export interface ToSvgOptions {
  size?: string | number
  className?: string
  label?: string
  [attr: string]: unknown
}

export declare const viewBox: string
export declare const icons: Record<IconName, string>
export declare const iconNames: IconName[]
export declare function getIcon (name: string): string | null
export declare function toSvg (name: IconName, options?: ToSvgOptions): string

${named.map((i) => `export declare const ${i.id}: Icon`).join('\n')}
`
  await fs.writeFile(path.join(distDir, 'index.d.ts'), dts)

  log.done('js: index.js, index.cjs, index.d.ts, icons.json')
}
