import fs from 'node:fs/promises'
import path from 'node:path'
import { dirs, font } from './config.mjs'
import { log } from './lib.mjs'
import { glyphDeclarations } from './css.mjs'

// Source of the custom element, it registers itself and carries the font and the codepoints.
export function elementSource (icons, woff2) {
  const glyphs = Object.fromEntries(icons.map((i) => [i.name, i.codepoint]))

  return `// Generated by build/element.mjs, do not edit.

const GLYPHS = ${JSON.stringify(glyphs)}

const FONT = '${woff2.toString('base64')}'

// The font is added to the document, browsers ignore a font declared inside a shadow tree.
document.fonts.add(new FontFace('${font.family}', Uint8Array.from(atob(FONT), (c) => c.charCodeAt(0))))

// The glyph is in a span of the shadow tree, where the styles of the page do not apply.
const sheet = new CSSStyleSheet()
sheet.replaceSync(\`
  :host {
    display: inline-flex;
    flex-shrink: 0;
  }
  :host([hidden]) { display: none; }
  span {
    ${glyphDeclarations.join('\n    ')}
    user-select: none;
    -webkit-user-select: none;
  }
\`)

class BulleIcon extends HTMLElement {
  static get observedAttributes () {
    return ['name', 'label']
  }

  #glyph = document.createElement('span')

  constructor () {
    super()
    this.attachShadow({ mode: 'open' }).append(this.#glyph)
    this.shadowRoot.adoptedStyleSheets = [sheet]
  }

  connectedCallback () {
    this.#render()
  }

  attributeChangedCallback () {
    if (this.isConnected) this.#render()
  }

  get name () {
    return this.getAttribute('name')
  }

  set name (value) {
    this.setAttribute('name', value)
  }

  #render () {
    const name = this.name
    const known = name != null && Object.hasOwn(GLYPHS, name)

    if (name && !known) console.warn(\`[bulle] unknown icon: \${name}\`)
    this.#glyph.textContent = known ? String.fromCodePoint(GLYPHS[name]) : ''

    const label = this.getAttribute('label')

    if (label) {
      this.setAttribute('role', 'img')
      this.setAttribute('aria-label', label)
      this.removeAttribute('aria-hidden')
    } else {
      this.setAttribute('aria-hidden', 'true')
      this.removeAttribute('role')
    }
  }
}

if (!customElements.get('bulle-icon')) {
  customElements.define('bulle-icon', BulleIcon)
}

export { BulleIcon }
export default BulleIcon
`
}

export async function buildElement (icons, woff2, { distDir = dirs.dist } = {}) {
  await fs.writeFile(path.join(distDir, 'bulle-icon.js'), elementSource(icons, woff2))
  log.done('element: bulle-icon.js')
}
