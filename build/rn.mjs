import fs from 'node:fs/promises'
import path from 'node:path'
import { dirs, font as cfg } from './config.mjs'
import { ensureDir, log } from './lib.mjs'

// iOS finds a font by its PostScript name and Android by its file name, so both are this one.
export const FAMILY = cfg.family.replace(/\s+/g, '')

// Writes the React Native component, the module of its font file and the font file.
export async function buildReactNative (icons, ttf, { distDir = dirs.dist } = {}) {
  const dir = path.join(distDir, 'react-native')
  await ensureDir(path.join(dir, 'fonts'))

  await fs.writeFile(path.join(dir, 'fonts', `${FAMILY}.ttf`), ttf)

  const glyphMap = Object.fromEntries(icons.map((i) => [i.name, i.codepoint]))

  const js = `// Generated by build/rn.mjs, do not edit.
import React from 'react'
import { Platform, Text } from 'react-native'

export const FONT_FAMILY = ${JSON.stringify(FAMILY)}

export const glyphMap = ${JSON.stringify(glyphMap)}

export const iconNames = Object.keys(glyphMap)

export function glyph (name) {
  if (!Object.prototype.hasOwnProperty.call(glyphMap, name)) return null
  return String.fromCodePoint(glyphMap[name])
}

// A Text with one glyph, inside another Text it has the size and the color of that text.
export function BulleIcon ({ name, size, color, style, ...rest }) {
  const character = glyph(name)

  if (character == null) {
    if (__DEV__) console.warn(\`[bulle] unknown icon: \${name}\`)
    return null
  }

  const glyphStyle = { fontFamily: FONT_FAMILY }

  if (size != null) glyphStyle.fontSize = size
  if (color != null) glyphStyle.color = color

  // Android pads a text box above and below the font, which moves the glyph off the line.
  if (Platform.OS === 'android') glyphStyle.includeFontPadding = false

  return React.createElement(
    Text,
    { accessible: false, allowFontScaling: false, ...rest, style: [glyphStyle, style] },
    character
  )
}

export default BulleIcon
`

  await fs.writeFile(path.join(dir, 'index.js'), js)

  const dts = `// Generated by build/rn.mjs, do not edit.
import type { ReactElement } from 'react'
import type { TextProps, StyleProp, TextStyle } from 'react-native'
import type { IconName } from '../index'

export declare const FONT_FAMILY: string
export declare const glyphMap: Record<IconName, number>
export declare const iconNames: IconName[]
export declare function glyph (name: IconName): string | null

export interface BulleIconProps extends Omit<TextProps, 'style' | 'children'> {
  name: IconName
  size?: number
  color?: string
  style?: StyleProp<TextStyle>
}

export declare function BulleIcon (props: BulleIconProps): ReactElement | null
export default BulleIcon
`

  await fs.writeFile(path.join(dir, 'index.d.ts'), dts)

  // The font file has its own module, an app that links the font does not bundle it again.
  await fs.writeFile(
    path.join(dir, 'font.js'),
    `// Generated by build/rn.mjs, do not edit.\nimport font from './fonts/${FAMILY}.ttf'\n\nexport default font\n`
  )

  await fs.writeFile(
    path.join(dir, 'font.d.ts'),
    '// Generated by build/rn.mjs, do not edit.\ndeclare const font: number\nexport default font\n'
  )

  log.done(`react-native: ${icons.length} glyphs`)
}
