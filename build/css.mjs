import fs from 'node:fs/promises'
import path from 'node:path'
import { dirs, font as cfg } from './config.mjs'
import { log } from './lib.mjs'

const hex = (cp) => `\\${cp.toString(16)}`

// Declarations of an element that shows a glyph, shared by the base class and the custom element.
export const glyphDeclarations = [
  `font-family: "${cfg.family}" !important;`,
  'font-style: normal;',
  'font-weight: 400;',
  'font-variant: normal;',
  'font-feature-settings: normal;',
  'text-transform: none;',
  'line-height: 1;',
  'letter-spacing: normal;',
  'speak: never;',
  'display: inline-block;',
  '-webkit-font-smoothing: antialiased;',
  '-moz-osx-font-smoothing: grayscale;'
]

// The stylesheet, with the font face of the given sources, the base class and one class per icon.
export function stylesheet (icons, fontSources) {
  const glyphs = icons
    .map((i) => `.${cfg.prefix}-${i.name}::before { content: "${hex(i.codepoint)}"; }`)
    .join('\n')

  return `/* Generated by build/css.mjs, do not edit. */

@font-face {
  font-family: "${cfg.family}";
  font-style: normal;
  font-weight: 400;
  font-display: block;
  src:
    ${fontSources.join(',\n    ')};
}

/* Glyphs extend ${cfg.descent / cfg.fontHeight}em below the baseline, no vertical-align. */
.${cfg.prefix} {
  ${glyphDeclarations.join('\n  ')}
}

.${cfg.prefix}::before {
  display: inline-block;
}

/* Inline <svg> and <use>, lowered like the glyphs. */
.${cfg.prefix}-svg {
  width: 1em;
  height: 1em;
  fill: currentColor;
  vertical-align: -${cfg.descent / cfg.fontHeight}em;
}

/* Fixed width, to align icons in lists and buttons. */
.${cfg.prefix}-fw::before {
  width: 1.25em;
  text-align: center;
}

/* Sizes relative to the surrounding text. */
.${cfg.prefix}-sm { font-size: 0.875em; }
.${cfg.prefix}-lg { font-size: 1.25em; }
.${cfg.prefix}-xl { font-size: 1.5em; }
.${cfg.prefix}-2x { font-size: 2em; }
.${cfg.prefix}-3x { font-size: 3em; }

.${cfg.prefix}-spin::before {
  display: inline-block;
  animation: ${cfg.prefix}-spin 1.4s linear infinite;
}

@keyframes ${cfg.prefix}-spin {
  to { transform: rotate(360deg); }
}

@media (prefers-reduced-motion: reduce) {
  .${cfg.prefix}-spin::before { animation: none; }
}

${glyphs}
`
}

export async function buildCss (icons) {
  const sources = [
    `url("./fonts/${cfg.basename}.woff2") format("woff2")`,
    `url("./fonts/${cfg.basename}.woff") format("woff")`,
    `url("./fonts/${cfg.basename}.ttf") format("truetype")`
  ]

  await fs.writeFile(path.join(dirs.dist, `${cfg.basename}.css`), stylesheet(icons, sources))
  log.done(`css: ${cfg.basename}.css`)
}
